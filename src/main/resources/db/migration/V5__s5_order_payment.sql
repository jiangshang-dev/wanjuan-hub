CREATE TABLE trade_order
(
    id               BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    order_no         VARCHAR(64) NOT NULL,
    idempotency_key  VARCHAR(80) NOT NULL,
    user_id          BIGINT UNSIGNED NOT NULL,
    resource_id      BIGINT UNSIGNED NOT NULL,
    total_amount     DECIMAL(18, 2) NOT NULL,
    currency         CHAR(3) NOT NULL DEFAULT 'CNY',
    client_type      VARCHAR(24) NOT NULL,
    status           VARCHAR(24) NOT NULL DEFAULT 'PENDING_PAYMENT',
    grant_status     VARCHAR(16) NOT NULL DEFAULT 'NONE',
    expire_at        DATETIME NOT NULL,
    paid_at          DATETIME DEFAULT NULL,
    closed_at        DATETIME DEFAULT NULL,
    close_reason     VARCHAR(255) DEFAULT NULL,
    version          INT UNSIGNED NOT NULL DEFAULT 0,
    create_time      DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time      DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uk_trade_order_no (order_no),
    UNIQUE KEY uk_trade_order_idempotency_key (idempotency_key),
    KEY idx_trade_order_user_created (user_id, create_time, id),
    KEY idx_trade_order_status_expire (status, expire_at),
    KEY idx_trade_order_resource (resource_id, user_id, status),
    CONSTRAINT fk_trade_order_user FOREIGN KEY (user_id) REFERENCES user_account (id),
    CONSTRAINT fk_trade_order_resource FOREIGN KEY (resource_id) REFERENCES resource_info (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE trade_order_item
(
    id            BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    order_id      BIGINT UNSIGNED NOT NULL,
    resource_id   BIGINT UNSIGNED NOT NULL,
    resource_name VARCHAR(120) NOT NULL,
    price         DECIMAL(18, 2) NOT NULL,
    owner_id      BIGINT UNSIGNED NOT NULL,
    create_time   DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time   DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uk_trade_order_item_order_resource (order_id, resource_id),
    KEY idx_trade_order_item_resource (resource_id, owner_id),
    CONSTRAINT fk_trade_order_item_order FOREIGN KEY (order_id) REFERENCES trade_order (id),
    CONSTRAINT fk_trade_order_item_resource FOREIGN KEY (resource_id) REFERENCES resource_info (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE trade_payment
(
    id                 BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    payment_no         VARCHAR(64) NOT NULL,
    order_id           BIGINT UNSIGNED NOT NULL,
    channel            VARCHAR(16) NOT NULL,
    scene              VARCHAR(16) NOT NULL,
    amount             DECIMAL(18, 2) NOT NULL,
    currency           CHAR(3) NOT NULL DEFAULT 'CNY',
    status             VARCHAR(24) NOT NULL DEFAULT 'CREATED',
    channel_trade_no   VARCHAR(128) DEFAULT NULL,
    form_html          MEDIUMTEXT DEFAULT NULL,
    code_url           TEXT DEFAULT NULL,
    h5_url             TEXT DEFAULT NULL,
    channel_status     VARCHAR(64) DEFAULT NULL,
    paid_at            DATETIME DEFAULT NULL,
    last_query_at      DATETIME DEFAULT NULL,
    error_message      VARCHAR(1000) DEFAULT NULL,
    version            INT UNSIGNED NOT NULL DEFAULT 0,
    create_time        DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time        DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uk_trade_payment_no (payment_no),
    UNIQUE KEY uk_trade_payment_order (order_id),
    UNIQUE KEY uk_trade_payment_channel_trade (channel, channel_trade_no),
    KEY idx_trade_payment_status_query (status, last_query_at),
    KEY idx_trade_payment_created (create_time, id),
    CONSTRAINT fk_trade_payment_order FOREIGN KEY (order_id) REFERENCES trade_order (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE trade_payment_notification
(
    id                 BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    notification_id    VARCHAR(192) NOT NULL,
    channel            VARCHAR(16) NOT NULL,
    payment_id         BIGINT UNSIGNED DEFAULT NULL,
    order_id           BIGINT UNSIGNED DEFAULT NULL,
    channel_trade_no   VARCHAR(128) DEFAULT NULL,
    event_type         VARCHAR(64) NOT NULL,
    process_status     VARCHAR(24) NOT NULL DEFAULT 'RECEIVED',
    raw_payload        MEDIUMTEXT NOT NULL,
    error_message      VARCHAR(1000) DEFAULT NULL,
    processed_at       DATETIME DEFAULT NULL,
    create_time        DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time        DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uk_trade_payment_notification_id (notification_id),
    KEY idx_trade_payment_notification_order (order_id, create_time),
    KEY idx_trade_payment_notification_status (process_status, create_time),
    CONSTRAINT fk_trade_payment_notification_order FOREIGN KEY (order_id) REFERENCES trade_order (id),
    CONSTRAINT fk_trade_payment_notification_payment FOREIGN KEY (payment_id) REFERENCES trade_payment (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE trade_refund
(
    id                  BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    refund_no           VARCHAR(64) NOT NULL,
    order_id            BIGINT UNSIGNED NOT NULL,
    payment_id          BIGINT UNSIGNED NOT NULL,
    user_id             BIGINT UNSIGNED NOT NULL,
    channel             VARCHAR(16) NOT NULL,
    amount              DECIMAL(18, 2) NOT NULL,
    currency            CHAR(3) NOT NULL DEFAULT 'CNY',
    reason              VARCHAR(500) NOT NULL,
    status              VARCHAR(24) NOT NULL DEFAULT 'PENDING_REVIEW',
    channel_refund_no   VARCHAR(128) DEFAULT NULL,
    channel_status      VARCHAR(64) DEFAULT NULL,
    reviewer_id         BIGINT UNSIGNED DEFAULT NULL,
    review_opinion      VARCHAR(1000) DEFAULT NULL,
    reviewed_at         DATETIME DEFAULT NULL,
    refunded_at         DATETIME DEFAULT NULL,
    entitlement_revoked TINYINT NOT NULL DEFAULT 0,
    error_message       VARCHAR(1000) DEFAULT NULL,
    version             INT UNSIGNED NOT NULL DEFAULT 0,
    create_time         DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time         DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uk_trade_refund_no (refund_no),
    UNIQUE KEY uk_trade_refund_order (order_id),
    UNIQUE KEY uk_trade_refund_channel_no (channel, channel_refund_no),
    KEY idx_trade_refund_user_created (user_id, create_time, id),
    KEY idx_trade_refund_status_created (status, create_time, id),
    CONSTRAINT fk_trade_refund_order FOREIGN KEY (order_id) REFERENCES trade_order (id),
    CONSTRAINT fk_trade_refund_payment FOREIGN KEY (payment_id) REFERENCES trade_payment (id),
    CONSTRAINT fk_trade_refund_user FOREIGN KEY (user_id) REFERENCES user_account (id),
    CONSTRAINT fk_trade_refund_reviewer FOREIGN KEY (reviewer_id) REFERENCES sys_admin (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE trade_reconciliation
(
    id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    reconciliation_no VARCHAR(64) NOT NULL,
    order_id          BIGINT UNSIGNED NOT NULL,
    payment_id        BIGINT UNSIGNED DEFAULT NULL,
    channel           VARCHAR(16) NOT NULL,
    triggered_by      VARCHAR(16) NOT NULL,
    result            VARCHAR(24) NOT NULL,
    expected_amount   DECIMAL(18, 2) NOT NULL,
    channel_amount    DECIMAL(18, 2) DEFAULT NULL,
    expected_status   VARCHAR(24) NOT NULL,
    channel_status    VARCHAR(64) DEFAULT NULL,
    channel_trade_no  VARCHAR(128) DEFAULT NULL,
    operator_id       BIGINT UNSIGNED DEFAULT NULL,
    detail            VARCHAR(1000) DEFAULT NULL,
    reconciled_at     DATETIME NOT NULL,
    create_time       DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time       DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uk_trade_reconciliation_no (reconciliation_no),
    KEY idx_trade_reconciliation_order_created (order_id, create_time, id),
    KEY idx_trade_reconciliation_result_created (result, create_time, id),
    CONSTRAINT fk_trade_reconciliation_order FOREIGN KEY (order_id) REFERENCES trade_order (id),
    CONSTRAINT fk_trade_reconciliation_payment FOREIGN KEY (payment_id) REFERENCES trade_payment (id),
    CONSTRAINT fk_trade_reconciliation_operator FOREIGN KEY (operator_id) REFERENCES sys_admin (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
